#!/usr/bin/env bash
# Rebuilds new_project_setup.sql from supabase/migrations (all of them, in order).
# Run after adding a migration:  bash supabase/scripts/make_new_project_setup.sh
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
OUT="${1:-$HERE/new_project_setup.sql}"
{
  cat <<'HEAD'
-- PicklePro: set up a NEW, EMPTY Supabase project in one go.
-- Paste the whole file into Supabase Dashboard -> SQL Editor -> New query -> Run.
--
-- It is every file in supabase/migrations, in order, so the project ends up the same as
-- one built with `supabase db push`. Use it ONLY on a new project: on an existing one,
-- use check_database.sql and the pickleproapp_upgrade_N.sql files instead.
-- If the SQL Editor says the query is too large, use `supabase link` + `supabase db push`.
-- Afterwards run check_database.sql: every row should say OK.
-- Generated by make_new_project_setup.sh; do not edit by hand.
HEAD
  for f in "$HERE"/../migrations/*.sql; do
    printf '\n\n-- ════════════════ %s ════════════════\n\n' "$(basename "$f")"
    cat "$f"
  done
} > "$OUT"
echo "wrote $OUT ($(wc -c < "$OUT") bytes)"
